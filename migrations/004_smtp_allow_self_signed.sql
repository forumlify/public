-- ============================================================
--  SMTP 增加「允许自签证书」开关
-- ------------------------------------------------------------
--  背景：邮件模块最初对所有 SMTP 服务器都关闭了 TLS 证书校验
--  （tls.rejectUnauthorized = false），以便兼容使用自签证书的自建
--  邮件服务器。但这会削弱安全性——对 Resend、QQ、Gmail 等使用可信
--  证书的正规服务商而言，关掉校验只会给中间人留下可乘之机。
--
--  现改为默认严格校验，仅在以下情况才放行自签证书：
--  部署者明确在后台打开该开关。
--
--  003 已在部分部署中执行过，因此这里单独追加一版，
--  让存量库也能拿到这个配置项。
-- ============================================================

INSERT INTO settings (key, value) VALUES ('smtp_allow_self_signed', 'false')
ON CONFLICT (key) DO NOTHING;
